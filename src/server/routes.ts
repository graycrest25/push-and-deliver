export function allowedRoute(method: string, path: string) {
  if (path.startsWith("/v1/marketplace/")) return false;
  // Never expose retired upload, withdrawal or private operator-key APIs.
  if (/^\/v1\/(uploads(?:\/|$)|payouts\/withdrawals(?:\/|$))/.test(path))
    return false;
  if (path.startsWith("/v1/support/tickets")) return false;
  if (path === "/v1/config" || path === "/v1/admin/config/ten_seconds")
    return false;
  if (path === "/v1/admin/users/super-admin") return false;
  return routes.some(
    ([verb, template]) =>
      verb === method &&
      new RegExp(
        "^" +
          template.replace("{part}", "[12]").replace(/\{[^}]+\}/g, "[^/]+") +
          "$",
      ).test(path),
  );
}
